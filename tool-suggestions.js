/* =========================================
   GET CURRENT PAGE
   ========================================= */

function getCurrentPage() {

    let path = window.location.pathname;

    let page = path.substring(
        path.lastIndexOf("/") + 1
    );

    /* Remove query string */
    page = page.split("?")[0];

    /* Remove hash */
    page = page.split("#")[0];

    /* If empty */
    if (!page) {
        page = "tool.html";
    }

    return page;
}


/* =========================================
   SHOW TOOL SUGGESTIONS
   ========================================= */

function showToolSuggestions() {

    const container =
        document.getElementById("toolSuggestions");

    if (!container) {
        return;
    }

    const currentPage =
        getCurrentPage();

    const suggestions =
        toolSuggestions[currentPage];

    if (!suggestions || suggestions.length === 0) {

        container.innerHTML = "";

        container.style.display = "none";

        return;
    }


    let html = `
        <div class="suggestions-title">
            <span>🛠️</span>
            <h2>Tool Suggestions</h2>
        </div>

        <div class="suggestions-grid">
    `;


    suggestions.forEach(function(tool) {

        html += `
            <div class="suggestion-card"
                 onclick="window.location.href='${tool[3]}'">

                <div class="suggestion-icon">
                    ${tool[0]}
                </div>

                <div class="suggestion-content">

                    <h3>
                        ${tool[1]}
                    </h3>

                    <p>
                        ${tool[2]}
                    </p>

                </div>

                <span class="suggestion-arrow">
                    →
                </span>

            </div>
        `;

    });


    html += `
        </div>
    `;


    container.innerHTML = html;

    container.style.display = "block";
}


/* =========================================
   START
   ========================================= */

function startToolSuggestions() {

    showToolSuggestions();

}


/* =========================================
   PAGE LOAD
   ========================================= */

if (document.readyState === "loading") {

    document.addEventListener(
        "DOMContentLoaded",
        startToolSuggestions
    );

} else {

    startToolSuggestions();

}
